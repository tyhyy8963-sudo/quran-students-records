--
--  مولَّد من هجرات المشروع نفسها (استخراج DDL حقيقي عبر SHOW CREATE TABLE على
--  MariaDB فعليّة بعد تشغيل `php artisan migrate` كاملًا) — لا مكتوب يدويًا،
--  فلا يمكن أن ينحرف عن الهجرات. يعكس حالة المشروع بعد السبرنتات 1–14:
--  إغلاق نظام الحسابات (مدير ينشئ حسابات المعلّمين، بلا تسجيل ذاتي ولا بريد
--  إلكتروني ولا استعادة كلمة مرور)، ونسبة الحفظ بترتيب الحفظ المعكوس
--  (الناس ≈ 1% … البقرة = 100%، والفاتحة مستثناة من العدّ).
--
--  الجداول: 10  |  الحسابات: 4 (مدير + 3 معلّمين)  |  الحلقات: 3
--  الطلاب: 26  |  السور: 114  |  السجلّ الزمني: 109 سطرًا
--  سجلّ الحضور: 85 سطرًا (آخر أسبوع لحلقة الفجر، مع انقطاع متتالٍ للطالب
--  #2 ليظهر مؤشّر "انقطاع" في اللوحة والتقارير فور الاستيراد مباشرة)
--  الترميز: utf8mb4 / utf8mb4_unicode_ci  (لازم للنصوص العربية)
--  متوافق مع: MySQL 5.7+ و MariaDB 10.3+
--
--  ملاحظة على S13: جدولا student_data وotp_verifications أُلغيا سابقًا، وأُضيف
--  إليهما الآن password_resets — لا استعادة ذاتية لكلمة المرور في منظومة مغلقة،
--  فالجدول كان سيحمل رموزًا صالحة بلا مسار يستهلكها. وعمودا email
--  وemail_verified_at حُذفا من users: لا بريد في النظام أصلًا.
--
--  الاستيراد:
--    mysql -u root -p < teacher_db.sql
--
--  ⚠  هذا الملف يحذف قاعدة البيانات `teacher_db` ثم يعيد إنشاءها — لا تُشغّله على
--     بيانات حقيقية. كلمة مرور كل الحسابات التجريبية: motabaa123
--     الدخول: admin (مدير) · abdulrahman · khaled (معلّمان) · majed (معطَّل عمدًا)
-- =============================================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';
SET time_zone = '+00:00';

DROP DATABASE IF EXISTS `teacher_db`;
CREATE DATABASE `teacher_db` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `teacher_db`;

-- -----------------------------------------------------------------------------
-- 1) حذف الجداول إن وُجدت (بترتيب يحترم المفاتيح الأجنبية)
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS `attendances`;
DROP TABLE IF EXISTS `recitation_logs`;
DROP TABLE IF EXISTS `students`;
DROP TABLE IF EXISTS `circles`;
DROP TABLE IF EXISTS `surahs`;
DROP TABLE IF EXISTS `jobs`;
DROP TABLE IF EXISTS `personal_access_tokens`;
DROP TABLE IF EXISTS `failed_jobs`;
DROP TABLE IF EXISTS `users`;
DROP TABLE IF EXISTS `migrations`;


-- =============================================================================
-- 2) البنية (DDL حقيقي مستخرَج من MariaDB بعد تشغيل الهجرات)
-- =============================================================================
-- -----------------------------------------------------------------------------
-- `migrations` — سجلّ الهجرات المنفَّذة، يمنع Laravel من إعادة تشغيلها
-- -----------------------------------------------------------------------------
CREATE TABLE `migrations` (
  `id` int(10) unsigned NOT NULL AUTO_INCREMENT,
  `migration` varchar(255) NOT NULL,
  `batch` int(11) NOT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `users` — الحسابات: مدير واحد + ثلاثة معلّمين (لا بريد إلكتروني في المنظومة)
-- -----------------------------------------------------------------------------
CREATE TABLE `users` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `name` varchar(255) NOT NULL,
  `username` varchar(50) DEFAULT NULL,
  `role` varchar(20) NOT NULL DEFAULT 'teacher',
  `is_active` tinyint(1) NOT NULL DEFAULT 1,
  `last_login_at` timestamp NULL DEFAULT NULL,
  `mosque` varchar(255) DEFAULT NULL,
  `classroom` varchar(255) DEFAULT NULL,
  `password` varchar(255) NOT NULL,
  `remember_token` varchar(100) DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `users_username_unique` (`username`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `surahs` — 114 سورة برواية حفص + رتبة كل سورة في ترتيب الحفظ المعكوس
-- -----------------------------------------------------------------------------
CREATE TABLE `surahs` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `number` tinyint(3) unsigned NOT NULL,
  `memorization_order` smallint(5) unsigned DEFAULT NULL,
  `name` varchar(255) NOT NULL,
  `ayah_count` smallint(5) unsigned NOT NULL,
  `excluded_from_progress` tinyint(1) NOT NULL DEFAULT 0,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `surahs_number_unique` (`number`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `circles` — الحلقات، كل حلقة لمعلّم واحد
-- -----------------------------------------------------------------------------
CREATE TABLE `circles` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `teacher_id` bigint(20) unsigned NOT NULL,
  `name` varchar(255) NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `circles_teacher_id_name_unique` (`teacher_id`,`name`),
  CONSTRAINT `circles_teacher_id_foreign` FOREIGN KEY (`teacher_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `students` — الطلاب مع الحلقة والحالة والحذف الناعم
-- -----------------------------------------------------------------------------
CREATE TABLE `students` (
  `student_id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `student_name` varchar(255) NOT NULL,
  `teacher_id` bigint(20) unsigned NOT NULL,
  `circle_id` bigint(20) unsigned DEFAULT NULL,
  `status` varchar(20) NOT NULL DEFAULT 'active',
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  `deleted_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`student_id`),
  KEY `students_teacher_id_foreign` (`teacher_id`),
  KEY `students_circle_id_foreign` (`circle_id`),
  CONSTRAINT `students_circle_id_foreign` FOREIGN KEY (`circle_id`) REFERENCES `circles` (`id`) ON DELETE SET NULL,
  CONSTRAINT `students_teacher_id_foreign` FOREIGN KEY (`teacher_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `recitation_logs` — السجلّ الزمني (حفظ/مراجعة/تسميع) — مصدر نسبة الحفظ
-- -----------------------------------------------------------------------------
CREATE TABLE `recitation_logs` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `student_id` bigint(20) unsigned NOT NULL,
  `surah_id` bigint(20) unsigned DEFAULT NULL,
  `from_ayah` smallint(5) unsigned DEFAULT NULL,
  `to_ayah` smallint(5) unsigned NOT NULL,
  `type` varchar(20) NOT NULL DEFAULT 'حفظ',
  `grade` varchar(20) DEFAULT NULL,
  `notes` text DEFAULT NULL,
  `logged_at` date NOT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `recitation_logs_surah_id_foreign` (`surah_id`),
  KEY `recitation_logs_student_id_logged_at_index` (`student_id`,`logged_at`),
  CONSTRAINT `recitation_logs_student_id_foreign` FOREIGN KEY (`student_id`) REFERENCES `students` (`student_id`) ON DELETE CASCADE,
  CONSTRAINT `recitation_logs_surah_id_foreign` FOREIGN KEY (`surah_id`) REFERENCES `surahs` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `attendances` — سطر واحد لكل (طالب، يوم) بأربع حالات
-- -----------------------------------------------------------------------------
CREATE TABLE `attendances` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `student_id` bigint(20) unsigned NOT NULL,
  `date` date NOT NULL,
  `status` varchar(20) NOT NULL,
  `notes` text DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `attendances_student_id_date_unique` (`student_id`,`date`),
  CONSTRAINT `attendances_student_id_foreign` FOREIGN KEY (`student_id`) REFERENCES `students` (`student_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `failed_jobs` — مهام الطابور التي استنفدت محاولاتها
-- -----------------------------------------------------------------------------
CREATE TABLE `failed_jobs` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `uuid` varchar(255) NOT NULL,
  `connection` text NOT NULL,
  `queue` text NOT NULL,
  `payload` longtext NOT NULL,
  `exception` longtext NOT NULL,
  `failed_at` timestamp NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`id`),
  UNIQUE KEY `failed_jobs_uuid_unique` (`uuid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `personal_access_tokens` — رموز Sanctum (غير مستعملة في الواجهة)
-- -----------------------------------------------------------------------------
CREATE TABLE `personal_access_tokens` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `tokenable_type` varchar(255) NOT NULL,
  `tokenable_id` bigint(20) unsigned NOT NULL,
  `name` varchar(255) NOT NULL,
  `token` varchar(64) NOT NULL,
  `abilities` text DEFAULT NULL,
  `last_used_at` timestamp NULL DEFAULT NULL,
  `expires_at` timestamp NULL DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `personal_access_tokens_token_unique` (`token`),
  KEY `personal_access_tokens_tokenable_type_tokenable_id_index` (`tokenable_type`,`tokenable_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- `jobs` — طابور المهام
-- -----------------------------------------------------------------------------
CREATE TABLE `jobs` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `queue` varchar(255) NOT NULL,
  `payload` longtext NOT NULL,
  `attempts` tinyint(3) unsigned NOT NULL,
  `reserved_at` int(10) unsigned DEFAULT NULL,
  `available_at` int(10) unsigned NOT NULL,
  `created_at` int(10) unsigned NOT NULL,
  PRIMARY KEY (`id`),
  KEY `jobs_queue_index` (`queue`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


